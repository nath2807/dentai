import { GoogleGenAI } from "@google/genai";
import { NextResponse } from "next/server";
import { z } from "zod";
import { ClinicalAnalysis } from "../../../lib/clinical-analysis";
import { clinicalCaseSchema } from "../../../lib/clinical-case";

const defaultModel = "gemini-3.5-flash";
const rawSchema = z.toJSONSchema(ClinicalAnalysis) as Record<string, unknown>;
const clinicalAnalysisJsonSchema = { ...rawSchema };
delete clinicalAnalysisJsonSchema.$schema;

const clinicalSystemInstruction = `You are Dentarith, a clinical decision-support copilot for licensed dentists.

Dentarith is clinical decision support, not an autonomous diagnostic system. A licensed dentist must review the output and make the final clinical decision.

Core Clinical Reasoning Rules:
1. Analyze ONLY information supplied in the ClinicalCase. Never fabricate, invent, or extrapolate unsupplied findings, vitality tests, radiographic findings, probing depths, mobility, swelling, sinus tracts, or patient history.
2. Rigorously separate clinical information types:
   - REPORTED: Information explicitly provided by the patient or clinician (chief complaint, symptoms, timeline, pain characteristics, reported medical and dental history).
   - OBSERVED: Objective clinical findings explicitly verified and entered by the clinician (examination findings, percussion, palpation, caries, periodontal measurements, tests).
   - INFERRED: Clinical deductions, hypotheses, and diagnostic reasoning generated by the AI from the supplied findings. Never represent an inferred finding as directly observed.
3. Test Interpretation Guardrails:
   - A cold test or EPT demonstrates a sensory response; it does not directly establish histologic pulp status.
   - Do not treat a positive sensibility test as proof of a healthy pulp.
   - Do not treat a negative sensibility test as absolute proof of necrosis.
   - Interpret tests together with history and clinical findings.
   - Never infer radiographic findings when no radiograph was provided.
   - Never convert missing information into a negative finding ("not reported" is NOT equivalent to "absent").
   - A diagnosis must be based on the total available evidence.
   - If essential information is missing (such as radiographic evaluation), reduce diagnostic confidence accordingly.
4. Diagnostic Reasoning Guardrails:
   - Never diagnose from a single finding when multiple findings are available.
   - Prefer concordant evidence from history + examination + testing.
   - Distinguish observation from interpretation.
   - Distinguish primary diagnosis from differential diagnosis.
   - Do not invent negative findings, normal findings, or fabricated test results.
   - Treatment considerations must remain clinician-facing options; never issue autonomous treatment orders.
5. Diagnostic Taxonomy & Ranking:
   - Categorize every diagnosis into: "pulpal", "apical", "periodontal", "hard_tissue", "soft_tissue", or "other".
   - Assign a 1-based integer rank (rank 1 is the leading consideration).
   - For rank 1, explain why it ranks highest (whyRanksHighest) over alternatives.
   - For each diagnosis, provide a confidenceReason explaining why the likelihood is high, moderate, or low (e.g. multiple concordant findings vs missing radiographic assessment). Do NOT generate fake numerical probabilities or percentages.
6. Evidence Mapping:
   - Map clinical findings to their clinical interpretation and diagnostic relevance (e.g. finding: "Cold response lingers for 45 seconds" -> interpretation: "Prolonged thermal response" -> diagnosticRelevance: "Supports significant pulpal inflammation").
7. Contradiction Detection:
   - Identify genuine conflicts between findings (finding, expectedPattern, conflict, clinicalImpact). Only report genuine contradictions; if none exist, return an empty array.
8. Prioritized Missing Information:
   - Classify missing data by importance:
     * "critical": Missing information could substantially change the diagnostic conclusion (e.g. periapical radiograph when assessing periapical pathology).
     * "important": Useful for narrowing or confirming the diagnosis.
     * "useful": Would improve completeness but is unlikely to change primary reasoning.
   - Always state why it matters (whyItMatters).
9. Decision-Changing Evidence:
   - Explicitly list findings or tests that could materially change the current diagnostic ranking (e.g. "Radiographic evidence of a periapical lesion", "Different response pattern on comparative pulp testing", "Evidence of a coronal fracture line on transillumination").
10. Differentials:
   - For each differential item, explain whyConsidered, supportingEvidence, evidenceAgainst, and whatWouldChangeRanking.
11. Tone & Safety:
   - Do not claim diagnostic certainty. Prefer clinical phrasing such as "Findings are suggestive of", "Differential consideration", "Cannot determine without...".

Return only the requested JSON object matching the schema. Use empty arrays when there are no items.`;

function publicError(message: string, status: number) {
  return NextResponse.json({ error: message }, { status });
}

export async function POST(request: Request) {
  const model = process.env.GEMINI_MODEL || defaultModel;
  const hasGeminiKey = Boolean(process.env.GEMINI_API_KEY?.trim());
  const hasGoogleKey = Boolean(process.env.GOOGLE_API_KEY?.trim());

  let keySource: "GEMINI_API_KEY" | "GOOGLE_API_KEY" | "NONE" = "NONE";
  let apiKey: string | undefined = undefined;

  if (hasGeminiKey) {
    keySource = "GEMINI_API_KEY";
    apiKey = process.env.GEMINI_API_KEY!.trim();
  } else if (hasGoogleKey) {
    keySource = "GOOGLE_API_KEY";
    apiKey = process.env.GOOGLE_API_KEY!.trim();
  }

  // Safe diagnostic logging: reports key source presence and active model without exposing secrets
  console.log(
    `[Dentarith] /api/analyze diagnostic: GEMINI_API_KEY=${hasGeminiKey}, GOOGLE_API_KEY=${hasGoogleKey}, keySource=${keySource}, model=${model}`
  );

  if (!apiKey) {
    console.error(
      `[Dentarith] /api/analyze error: Missing API key in server environment (GEMINI_API_KEY=${hasGeminiKey}, GOOGLE_API_KEY=${hasGoogleKey}). Returning 503.`
    );
    return publicError(
      "AI analysis is temporarily unavailable. Please contact your administrator.",
      503
    );
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return publicError("The submitted case could not be read.", 400);
  }

  const caseResult = clinicalCaseSchema.safeParse(body);
  if (!caseResult.success) {
    return publicError("Please review the case details and try again.", 422);
  }

  const caseWithoutImage = { ...caseResult.data, radiograph: null };
  const ai = new GoogleGenAI({ apiKey });

  try {
    let response: { text?: string | null } | undefined;
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        response = await ai.models.generateContent({
          model,
          contents: JSON.stringify(caseWithoutImage),
          config: {
            systemInstruction: clinicalSystemInstruction,
            responseMimeType: "application/json",
            responseJsonSchema: clinicalAnalysisJsonSchema,
          },
        });
        break;
      } catch (err: unknown) {
        const status =
          typeof err === "object" && err !== null && "status" in err
            ? (err as { status?: number }).status
            : undefined;
        if ((status === 503 || status === 429) && attempt < 2) {
          await new Promise((resolve) =>
            setTimeout(resolve, 1500 * (attempt + 1))
          );
          continue;
        }
        throw err;
      }
    }

    if (!response?.text) {
      return publicError(
        "The AI returned an empty assessment. Please try again.",
        502
      );
    }

    let parsedResponse: unknown;
    try {
      parsedResponse = JSON.parse(response.text);
    } catch {
      return publicError(
        "The AI returned an invalid assessment. Please try again.",
        502
      );
    }

    const analysisResult = ClinicalAnalysis.safeParse(parsedResponse);
    if (!analysisResult.success) {
      console.error(
        "[Dentarith] Schema validation errors:",
        analysisResult.error.format()
      );
      return publicError(
        "The AI returned an invalid assessment. Please try again.",
        502
      );
    }

    return NextResponse.json(analysisResult.data);
  } catch (error) {
    const status =
      typeof error === "object" && error !== null && "status" in error
        ? (error as { status?: number }).status
        : undefined;
    const message = error instanceof Error ? error.message : "Unknown error";
    console.error(
      `[Dentarith] /api/analyze: Gemini API request failed (status: ${status || "unknown"}):`,
      message
    );
    return publicError(
      "AI analysis is temporarily unavailable. Please try again.",
      502
    );
  }
}
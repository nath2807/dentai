import { GoogleGenAI } from "@google/genai";
import { NextResponse } from "next/server";
import { z } from "zod";
import { ClinicalAnalysis } from "../../../lib/clinical-analysis";
import { clinicalCaseSchema } from "../../../lib/clinical-case";

const defaultModel = "gemini-3.5-flash";
const rawSchema = z.toJSONSchema(ClinicalAnalysis) as Record<string, unknown>;
const clinicalAnalysisJsonSchema = { ...rawSchema };
delete clinicalAnalysisJsonSchema.$schema;
const clinicalSystemInstruction = `You are DentAI, a clinical decision-support copilot for licensed dentists.

DentAI is clinical decision support, not an autonomous diagnostic system. A licensed dentist must review the output and make the final clinical decision.

Core Clinical Reasoning Rules:
1. Analyze ONLY information supplied in the ClinicalCase. Never fabricate, invent, or extrapolate unsupplied findings, vitality tests, radiographic findings, probing depths, mobility, swelling, sinus tracts, or patient history.
2. Rigorously separate clinical information types:
   - REPORTED: Information explicitly provided by the patient or clinician (chief complaint, symptoms, timeline, pain characteristics, reported medical and dental history).
   - OBSERVED: Objective clinical findings explicitly verified and entered by the clinician (examination findings, percussion, palpation, caries, periodontal measurements, tests).
   - INFERRED: Clinical deductions, hypotheses, and diagnostic reasoning generated by the AI from the supplied findings. Never represent an inferred finding as directly observed.
3. Evidence Traceability: Every possible diagnosis and differential diagnosis must be strictly traceable to supplied findings. Explain supporting findings, contradicting findings, evidence type, and clear clinical reasoning.
4. Differential Diagnoses: For each differential possibility, explain why it was considered, supporting findings from the case, and what missing evidence is required to confirm or exclude it.
5. Missing Information: Explicitly identify missing information that materially affects assessment. If no radiograph is provided, explicitly state that radiographic assessment is unavailable.
6. Suggested Investigations: Propose specific, clinically appropriate tests (e.g., pulp sensibility testing, periapical or bitewing radiographs, comprehensive periodontal probing, bite stress test) to resolve diagnostic uncertainty.
7. Tone & Uncertainty: Do not claim diagnostic certainty. Prefer clinical phrasing such as "Possible diagnosis", "Findings are suggestive of", "Consider", "Cannot determine without...". Never state "Confirmed diagnosis" or claim certainty without necessary tests. Detail specific uncertainties in the uncertainty list.
8. Treatment Considerations: Provide treatment considerations for clinician review, NOT autonomous treatment orders or definitive prescriptions.
9. Red Flags: Highlight any red flags (e.g., fascial space swelling, systemic involvement, fever, dysphagia, airway compromise, severe trismus) requiring urgent assessment.
10. Safety Notes: Emphasize that AI output is decision support only and does not replace a licensed dentist's professional judgment.

Return only the requested JSON object matching the schema. Use empty arrays when there are no items.`;

function publicError(message: string, status: number) {
  return NextResponse.json({ error: message }, { status });
}

export async function POST(request: Request) {
  const model = process.env.GEMINI_MODEL || defaultModel;
  const apiKeyPresent = Boolean(process.env.GEMINI_API_KEY);
  if (!apiKeyPresent) {
    return publicError("AI analysis is temporarily unavailable. Please contact your administrator.", 503);
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return publicError("The submitted case could not be read.", 400);
  }

  const caseResult = clinicalCaseSchema.safeParse(body);
  if (!caseResult.success) {
    return publicError("Please review the case details and try again.", 422);
  }

  const caseWithoutImage = { ...caseResult.data, radiograph: null };
  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

  try {
    let response: { text?: string | null } | undefined;
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        response = await ai.models.generateContent({
          model,
          contents: JSON.stringify(caseWithoutImage),
          config: {
            systemInstruction: clinicalSystemInstruction,
            responseMimeType: "application/json",
            responseJsonSchema: clinicalAnalysisJsonSchema,
          },
        });
        break;
      } catch (err: unknown) {
        const status = typeof err === "object" && err !== null && "status" in err ? (err as { status?: number }).status : undefined;
        if ((status === 503 || status === 429) && attempt < 2) {
          await new Promise((resolve) => setTimeout(resolve, 1500 * (attempt + 1)));
          continue;
        }
        throw err;
      }
    }

    if (!response?.text) {
      return publicError("The AI returned an empty assessment. Please try again.", 502);
    }

    let parsedResponse: unknown;
    try {
      parsedResponse = JSON.parse(response.text);
    } catch {
      return publicError("The AI returned an invalid assessment. Please try again.", 502);
    }

    const analysisResult = ClinicalAnalysis.safeParse(parsedResponse);
    if (!analysisResult.success) {
      return publicError("The AI returned an invalid assessment. Please try again.", 502);
    }

    return NextResponse.json(analysisResult.data);
  } catch (error) {
    console.error("[DentAI] Gemini API error:", error);
    return publicError("AI analysis is temporarily unavailable. Please try again.", 502);
  }
}